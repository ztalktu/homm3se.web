export interface FactionBuildings {
  /**
   * Rows of the town hall screen, top to bottom. Each slot lists the buildings it shows in turn:
   * the first one, then what replaces it (Village Hall, Town Hall, City Hall, Capitol).
   */
  readonly hall: readonly (readonly (readonly number[])[])[];
  /** Buildings that must stand before this one; only the direct ones. */
  readonly requires: Readonly<Partial<Record<number, readonly number[]>>>;
  /** Buildings whose bit an upgrade clears in the first mask (it stays in the full one). */
  readonly replaces: Readonly<Partial<Record<number, readonly number[]>>>;
  readonly guildMax: number;
  /** Horde buildings and the dwelling level whose growth they raise. */
  readonly hordes: Readonly<Partial<Record<number, number>>>;
  /** Town buildings that are dwellings, with their level: the Gunpowder Warehouse, the Gantry. */
  readonly extraDwellings?: Readonly<Partial<Record<number, number>>>;
}

