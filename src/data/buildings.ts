const CONFLUX = 8;
/** Mage guild levels 1–5 are buildings 0–4. */
const MAGE_GUILD_LEVELS = 5;
const FACTORY = 10;

export type BuildingKind =
  | 'mageGuild'
  | 'tavern'
  | 'shipyard'
  | 'fort'
  | 'townHall'
  | 'market'
  | 'blacksmith'
  | 'horde'
  | 'grail'
  | 'dwelling'
  | 'special';

/** What sort of building an id is in a faction, with the level of a dwelling. */
export function buildingKind(
  id: number,
  faction: number,
  buildings: FactionBuildings,
): { kind: BuildingKind; level?: number } {
  const extra = buildings.extraDwellings?.[id];
  if (extra !== undefined) {
    return { kind: 'dwelling', level: extra };
  }
  if (id >= BUILDING.dwelling1) {
    return { kind: 'dwelling', level: ((id - BUILDING.dwelling1) % 7) + 1 };
  }
  if (buildings.hordes[id] !== undefined) {
    return { kind: 'horde' };
  }
  if (id < BUILDING.mageGuild1 + MAGE_GUILD_LEVELS) {
    return { kind: 'mageGuild' };
  }
  switch (id) {
    case BUILDING.tavern:
      return { kind: 'tavern' };
    case BUILDING.shipyard:
      // The Factory has its Mana Generator in that slot.
      return { kind: faction === FACTORY ? 'special' : 'shipyard' };
    case BUILDING.fort:
    case BUILDING.citadel:
    case BUILDING.castle:
      return { kind: 'fort' };
    case BUILDING.villageHall:
    case BUILDING.townHall:
    case BUILDING.cityHall:
    case BUILDING.capitol:
      return { kind: 'townHall' };
    case BUILDING.marketplace:
    case BUILDING.resourceSilo:
      return { kind: 'market' };
    case BUILDING.blacksmith:
      return { kind: 'blacksmith' };
    case BUILDING.grail:
      return { kind: 'grail' };
    default:
      return { kind: 'special' };
  }
}

/** The buildings of a faction in an edition's saves, or undefined for an unknown faction. */
export function factionBuildings(faction: number, edition: Edition): FactionBuildings | undefined {
  const base = FACTIONS[faction];
  if (!base || faction !== CONFLUX || edition !== 'hornOfTheAbyss') {
    return base;
  }
  return {
    hall: HOTA_CONFLUX.hall,
    requires: { ...base.requires, ...HOTA_CONFLUX.requires },
    replaces: { ...base.replaces, ...HOTA_CONFLUX.replaces },
    guildMax: base.guildMax,
    hordes: { ...base.hordes, ...HOTA_CONFLUX.hordes },
  };
}
